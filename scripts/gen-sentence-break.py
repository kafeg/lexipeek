#!/usr/bin/env python3
"""Writes core/src/mt/sentence_break.inc from Unicode's SentenceBreakProperty.txt (UAX #29): sorted code point ranges."""
import re, sys

src, out = sys.argv[1], sys.argv[2]
ranges = []
for line in open(src, encoding="utf-8"):
    m = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)", line)
    if m:
        lo = int(m[1], 16)
        ranges.append([lo, int(m[2], 16) if m[2] else lo, m[3]])
ranges.sort()
merged = []
for r in ranges:
    if merged and merged[-1][2] == r[2] and merged[-1][1] + 1 == r[0]:
        merged[-1][1] = r[1]
    else:
        merged.append(r)
version = re.search(r"SentenceBreakProperty-([\d.]+)\.txt", open(src, encoding="utf-8").readline())
with open(out, "w", encoding="utf-8") as f:
    f.write(f"// Generated by scripts/gen-sentence-break.py from SentenceBreakProperty-{version[1] if version else '?'}.txt; do not edit.\n")
    for lo, hi, p in merged:
        f.write(f"{{0x{lo:X}, 0x{hi:X}, SB::{p}}},\n")
print(len(merged), "ranges")
